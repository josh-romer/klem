use klem::{Analysis, Lemmatizer};
use unicode_normalization::UnicodeNormalization;

fn has_path(analyses: &[Analysis], heads: &[&str], forms: &[&str]) -> bool {
    analyses.iter().any(|a| {
        a.lemmas
            .iter()
            .map(|l| l.text.as_str())
            .eq(heads.iter().copied())
            && a.morphemes
                .iter()
                .map(|m| m.form.as_str())
                .eq(forms.iter().copied())
            && a.rules.iter().any(|r| r == "ending.literary_question_go")
    })
}

#[test]
fn original_dictionary_targets_recover_whole_question_endings() {
    let engine = Lemmatizer::new();
    let cases: &[(&str, &[&str], &[&str])] = &[
        ("몇인고", &["몇", "이다"], &["은고"]),
        ("뻔뻔한고", &["뻔뻔하다"], &["은고"]),
        ("더딘고", &["더디다"], &["은고"]),
        ("물건인고", &["물건", "이다"], &["은고"]),
        ("일인고", &["일", "이다"], &["은고"]),
        ("예쁜고", &["예쁘다"], &["은고"]),
        ("아둔한고", &["아둔하다"], &["은고"]),
        ("건고", &["것", "이다"], &["은고"]),
        ("고생인고", &["고생", "이다"], &["은고"]),
        ("훌륭한고", &["훌륭하다"], &["은고"]),
        ("잘못인고", &["잘못", "이다"], &["은고"]),
        ("것인고", &["것", "이다"], &["은고"]),
        ("찾아왔던고", &["찾아오다"], &["었", "던고"]),
        ("걸리던고", &["걸리다"], &["던고"]),
        ("있었던고", &["있다"], &["었", "던고"]),
        ("않았던고", &["않다"], &["었", "던고"]),
        ("했던고", &["하다"], &["었", "던고"]),
        ("왔던고", &["오다"], &["었", "던고"]),
        ("그리웠던고", &["그립다"], &["었", "던고"]),
        ("누구시던고", &["누구", "이다"], &["시", "던고"]),
        ("갔던고", &["가다"], &["었", "던고"]),
        ("가는고", &["가다"], &["는고"]),
        ("있는고", &["있다"], &["는고"]),
        ("바라는고", &["바라다"], &["는고"]),
        ("하는고", &["하다"], &["는고"]),
        ("되는고", &["되다"], &["는고"]),
        ("됐는고", &["되다"], &["었", "는고"]),
        ("않았는고", &["않다"], &["었", "는고"]),
        ("슬퍼하는고", &["슬퍼하다"], &["는고"]),
        ("높은고", &["높다"], &["은고"]),
        ("좋은고", &["좋다"], &["은고"]),
        ("얕은고", &["얕다"], &["은고"]),
        ("괜찮은고", &["괜찮다"], &["은고"]),
        ("깊은고", &["깊다"], &["은고"]),
        ("많은고", &["많다"], &["은고"]),
    ];
    for (word, heads, forms) in cases {
        for text in [word.to_string(), word.nfd().collect()] {
            let actual = engine.analyze_word(&text).unwrap();
            assert!(
                has_path(&actual.analyses, heads, forms),
                "{word}: {actual:?}"
            );
        }
    }
}
