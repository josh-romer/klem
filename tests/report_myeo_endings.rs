use klem::{Analysis, Lemmatizer};
use unicode_normalization::UnicodeNormalization;
fn path(a: &Analysis, l: &[&str], m: &[&str]) -> bool {
    a.lemmas
        .iter()
        .map(|x| x.text.as_str())
        .eq(l.iter().copied())
        && a.morphemes
            .iter()
            .map(|x| x.form.as_str())
            .eq(m.iter().copied())
}
