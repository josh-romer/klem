#[test]
fn report_myeo_components_do_not_invent_a_reporting_verb() {
    for word in [
        "먹는다며",
        "학생이라면서",
        "먹으라면서",
        "먹자며",
        "먹었느냐면서",
    ] {
        let result = Lemmatizer::new().analyze_word(word).unwrap();
        assert!(
            result
                .analyses
                .iter()
                .filter(|a| a.rules.iter().any(|r| r == "ending.reporting_myeo"))
                .all(|a| a.lemmas.iter().all(|l| l.text != "하다"))
        );
    }
}
